import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';

export const supportedLanguages = ['ru', 'kk'] as const;
export type AppLanguage = (typeof supportedLanguages)[number];

const LANGUAGE_STORAGE_KEY = 'app-language';
const DEFAULT_LANGUAGE: AppLanguage = 'ru';

function isSupportedLanguage(value: string | null): value is AppLanguage {
  return supportedLanguages.includes(value as AppLanguage);
}

function detectLanguage(): AppLanguage {
  if (typeof window === 'undefined') {
    return DEFAULT_LANGUAGE;
  }

  const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (isSupportedLanguage(savedLanguage)) {
    return savedLanguage;
  }

  return window.navigator.language.toLowerCase().startsWith('kk') ? 'kk' : DEFAULT_LANGUAGE;
}

